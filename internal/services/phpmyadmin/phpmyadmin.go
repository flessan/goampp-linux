//go:build windows

// Package phpmyadmin registers phpMyAdmin with the download catalogue:
// where to get it, how to find the newest build and how to set it up.
package phpmyadmin

import (
	cryptorand "crypto/rand"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"goampp/internal/packages"
)

func init() {
	packages.Register("phpMyAdmin", packages.DownloadSpec{
		Version:    "5.2.3",
		URL:        "https://files.phpmyadmin.net/phpMyAdmin/5.2.3/phpMyAdmin-5.2.3-all-languages.zip",
		FileName:   "phpMyAdmin-5.2.3-all-languages.zip",
		InstallDir: "www/phpmyadmin",
		StripTop:   "phpMyAdmin-5.2.3-all-languages/",
		Kind:       packages.Zip,
		CheckFile:  "index.php",
		Notes:      "Served by Apache — make sure Apache's DocumentRoot points at {base}/www.",
		PostInstall: func(installDir string, log func(string)) error {

			target := filepath.Join(installDir, "config.inc.php")
			var data []byte
			if b, err := os.ReadFile(target); err == nil {
				data = b
			} else {
				sample := filepath.Join(installDir, "config.sample.inc.php")
				b, derr := os.ReadFile(sample)
				if derr != nil {
					return nil
				}
				data = b
				log("  created config.inc.php from sample")
			}

			var secret [24]byte
			if _, err := cryptorand.Read(secret[:]); err == nil {
				enc := base64.StdEncoding.EncodeToString(secret[:])
				reBf := regexp.MustCompile(`(?m)^\$cfg\['blowfish_secret'\]\s*=\s*'[^']*';.*$`)
				data = reBf.ReplaceAllLiteral(data,
					[]byte(`$cfg['blowfish_secret'] = '`+enc+`'; /* auto-generated by GoAMPP */`))
			}

			reAllow := regexp.MustCompile(`(?m)^\$cfg\['Servers'\]\[\$i\]\['AllowNoPassword'\]\s*=\s*(?:true|false);.*$`)
			data = reAllow.ReplaceAllLiteral(data,
				[]byte(`$cfg['Servers'][$i]['AllowNoPassword'] = true; /* local dev — empty root password is fine */`))

			log("  patched config.inc.php (blowfish_secret, AllowNoPassword)")
			return os.WriteFile(target, data, 0o644)
		},
	}, resolvePhpMyAdminLatest)
}

type phpMyAdminVersion struct {
	Version string `json:"version"`
}

func resolvePhpMyAdminLatest(log func(string)) (urlOut, fileName, stripTop, version string, err error) {
	const apiURL = "https://www.phpmyadmin.net/home_page/version.json"
	log("  resolving latest phpMyAdmin stable release ...")
	req, err := http.NewRequest(http.MethodGet, apiURL, nil)
	if err != nil {
		return "", "", "", "", err
	}
	req.Header.Set("User-Agent", "GoAMPP")
	resp, err := packages.LatestHTTPClient.Do(req)
	if err != nil {
		return "", "", "", "", err
	}
	defer resp.Body.Close()
	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		return "", "", "", "", fmt.Errorf("phpMyAdmin version API returned HTTP %d", resp.StatusCode)
	}
	var data phpMyAdminVersion
	if err := json.NewDecoder(resp.Body).Decode(&data); err != nil {
		return "", "", "", "", err
	}
	if data.Version == "" {
		return "", "", "", "", fmt.Errorf("phpMyAdmin version missing")
	}
	file := fmt.Sprintf("phpMyAdmin-%s-all-languages.zip", data.Version)
	dlURL := fmt.Sprintf("https://files.phpmyadmin.net/phpMyAdmin/%s/%s", data.Version, file)
	return dlURL, file, strings.TrimSuffix(file, ".zip") + "/", data.Version, nil
}
